"""Agent 10 - Final Output.

Re-renders every document now that test evidence exists and writes the change
package to disk: requirement, design, impact spreadsheet, SQL, tests, rollback,
PR description, release notes, validation report and a machine readable
manifest of the whole run.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

from ..context import ChangeContext
from ..models import ChangePackage, TestSuite
from ..writers import markdown_to_blocks, write_pdf, write_xlsx
from .a04_sql_generation import deployment_script
from .a05_documentation import refresh_documents
from .base import Agent

PACKAGE_DIRNAME = "Change_Request"


class FinalOutputAgent(Agent):
    name = "final_output"
    step = 10

    def execute(self, context: ChangeContext) -> str:
        refresh_documents(context)
        root = context.options.resolved_output() / PACKAGE_DIRNAME
        root.mkdir(parents=True, exist_ok=True)
        written: list[str] = []

        for filename, content in context.documents.items():
            written.append(self._write_text(root / filename, content))

        written.append(self._write_text(root / "Generated_SQL.sql", deployment_script(context)))
        if context.change_set:
            written.append(self._write_text(root / "Rollback_Script.sql", context.change_set.rollback_sql))
        written.append(self._write_text(root / "Unit_Tests.sql", self._suite_sql(context, context.unit_suite, "Unit tests")))
        written.append(
            self._write_text(
                root / "Integration_Tests.sql",
                self._suite_sql(context, context.integration_suite, "Integration tests"),
            )
        )
        if context.power_bi:
            written.append(self._write_text(root / "PowerBI_Change_Plan.md", self._power_bi_markdown(context)))
        if context.checklist:
            written.append(self._write_text(root / "Deployment_Checklist.md", self._checklist_markdown(context)))

        written.append(self._write_impact_workbook(context, root))
        written.append(self._write_impact_csv(context, root))
        written.append(self._write_validation_pdf(context, root))
        written.append(self._write_manifest(context, root))

        package = ChangePackage(root=str(root), files=sorted(written))
        context.package = package
        return f"wrote {len(package.files)} artifacts to {root}"

    # -- writers -----------------------------------------------------------
    @staticmethod
    def _write_text(path: Path, content: str) -> str:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content if content.endswith("\n") else content + "\n", encoding="utf-8")
        return path.name

    def _suite_sql(self, context: ChangeContext, suite: TestSuite | None, title: str) -> str:
        request = context.request
        header = [
            f"-- {title}",
            f"-- Request: {request.request_id} - {request.raw_request}" if request else "-- Request: unparsed",
            "-- Generated by the RCM change automation platform.",
            "",
        ]
        if suite is None or not suite.cases:
            return "\n".join(header + ["-- No cases were generated."])

        run = context.unit_run if suite is context.unit_suite else context.integration_run
        results = {result.name: result for result in (run.results if run else [])}

        blocks = ["\n".join(header), f"-- Suite: {suite.name}", f"-- {suite.description}", ""]
        for case in suite.cases:
            result = results.get(case.name)
            status = result.status.value if result else "not executed"
            observed = f" | observed: {result.actual}" if result and result.actual else ""
            blocks.append(
                f"-- [{case.category}] {case.name}\n"
                f"-- Expectation: {case.expectation}\n"
                f"-- Severity: {case.severity.value} | Sandbox result: {status}{observed}\n"
                f"{case.sql.rstrip()}\n"
            )
        return "\n".join(blocks)

    def _impact_rows(self, context: ChangeContext) -> list[list[str]]:
        impact = context.impact
        rows = [["Object", "Type", "Impact", "Layer", "Risk", "Owner", "Rationale"]]
        if impact:
            rows += [
                [
                    item.object_name,
                    item.object_type,
                    item.action.value,
                    item.layer,
                    item.risk,
                    item.owner,
                    item.rationale,
                ]
                for item in impact.items
            ]
        return rows

    def _write_impact_workbook(self, context: ChangeContext, root: Path) -> str:
        impact = context.impact
        sheets: dict[str, list[list[object]]] = {"Impact Matrix": self._impact_rows(context)}

        lineage_rows: list[list[object]] = [["Step", "Object", "Type", "Layer"]]
        if impact:
            lineage_rows += [
                [index, name, context.repo.object_type(name), context.repo.layer_of(name)]
                for index, name in enumerate(impact.propagation_path, start=1)
            ]
        sheets["Lineage Path"] = lineage_rows

        plan = context.power_bi
        power_bi_rows: list[list[object]] = [["Target", "Type", "Action", "Detail"]]
        if plan:
            power_bi_rows += [[c.target, c.target_type, c.action, c.detail] for c in plan.changes]
        sheets["Power BI"] = power_bi_rows

        test_rows: list[list[object]] = [["Suite", "Test", "Category", "Status", "Expectation", "Observed"]]
        for run in (context.unit_run, context.integration_run):
            if not run:
                continue
            test_rows += [
                [run.suite, r.name, r.category, r.status.value, r.expectation, r.actual]
                for r in run.results
            ]
        sheets["Tests"] = test_rows

        reconciliation_rows: list[list[object]] = [["Metric", "Before", "After", "Delta", "Result"]]
        if context.reconciliation:
            reconciliation_rows += [
                [line.metric, line.before, line.after, line.difference, "PASS" if line.matched else "FAIL"]
                for line in context.reconciliation.lines
            ]
        sheets["Reconciliation"] = reconciliation_rows

        write_xlsx(root / "Impact_Analysis.xlsx", sheets)
        return "Impact_Analysis.xlsx"

    def _write_impact_csv(self, context: ChangeContext, root: Path) -> str:
        path = root / "Impact_Analysis.csv"
        with path.open("w", newline="", encoding="utf-8") as handle:
            csv.writer(handle).writerows(self._impact_rows(context))
        return path.name

    def _write_validation_pdf(self, context: ChangeContext, root: Path) -> str:
        markdown = context.documents.get("Validation_Report.md", "")
        write_pdf(root / "Validation_Report.pdf", markdown_to_blocks(markdown))
        return "Validation_Report.pdf"

    def _write_manifest(self, context: ChangeContext, root: Path) -> str:
        manifest = {
            "request": context.request.to_dict() if context.request else None,
            "metadata": context.metadata.to_dict() if context.metadata else None,
            "impact": context.impact.to_dict() if context.impact else None,
            "change_set": context.change_set.to_dict() if context.change_set else None,
            "unit_tests": context.unit_run.to_dict() if context.unit_run else None,
            "integration_tests": context.integration_run.to_dict() if context.integration_run else None,
            "reconciliation": context.reconciliation.to_dict() if context.reconciliation else None,
            "power_bi": context.power_bi.to_dict() if context.power_bi else None,
            "checklist": context.checklist.to_dict() if context.checklist else None,
            "agents": [report.to_dict() for report in context.reports],
            "warnings": context.warnings,
        }
        path = root / "Run_Manifest.json"
        path.write_text(json.dumps(manifest, indent=2, default=str) + "\n", encoding="utf-8")
        return path.name

    # -- markdown helpers ---------------------------------------------------
    @staticmethod
    def _power_bi_markdown(context: ChangeContext) -> str:
        plan = context.power_bi
        assert plan is not None
        lines = [
            f"# Power BI Change Plan - {plan.report}",
            "",
            f"**Dataset:** {plan.dataset}  ",
            f"**Workspace:** {plan.workspace}  ",
            f"**Refresh required:** {'yes' if plan.refresh_required else 'no'}",
            "",
            "## Actions",
            "",
            "| Target | Type | Action | Detail |",
            "| --- | --- | --- | --- |",
        ]
        lines += [f"| {c.target} | {c.target_type} | {c.action} | {c.detail} |" for c in plan.changes]
        lines += [
            "",
            "## Impacted measures",
            "",
            "\n".join(f"- {m}" for m in plan.impacted_measures) or "_None_",
            "",
            "## Impacted relationships",
            "",
            "\n".join(f"- {r}" for r in plan.impacted_relationships) or "_None_",
            "",
            "## Impacted visuals",
            "",
            "\n".join(f"- {v}" for v in plan.impacted_visuals) or "_None_",
            "",
            "## Semantic model definition (TMDL)",
            "",
            "```tmdl",
            plan.tmdl_snippet.strip() or "-- no column added",
            "```",
            "",
        ]
        return "\n".join(lines)

    @staticmethod
    def _checklist_markdown(context: ChangeContext) -> str:
        checklist = context.checklist
        assert checklist is not None
        lines = ["# Deployment Readiness Checklist", ""]
        for section in checklist.sections():
            lines += [f"## {section}", ""]
            for item in checklist.items:
                if item.section != section:
                    continue
                detail = f" - {item.detail}" if item.detail else ""
                lines.append(f"- {item.marker} {item.item}{detail}")
            lines.append("")
        lines += [
            f"**Verdict:** {'READY FOR DEPLOYMENT' if checklist.ready else 'BLOCKED'}",
            "",
        ]
        if checklist.blockers:
            lines += ["## Blockers", "", "\n".join(f"- {b}" for b in checklist.blockers), ""]
        return "\n".join(lines)
